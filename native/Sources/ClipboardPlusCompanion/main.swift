@MainActor
final class ClipboardMonitor {
    private let pasteboard = NSPasteboard.general
    private let store: CompanionStore
    private var timer: Timer?
    private var lastChangeCount: Int
    var onCapture: ((NativeClip) -> Void)?

    init(store: CompanionStore) {
        self.store = store
        self.lastChangeCount = pasteboard.changeCount
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.35, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.checkClipboard() }
        }
    }

    func notePasteboardWrite() {
        lastChangeCount = pasteboard.changeCount
    }

    private func checkClipboard() {
        let currentChangeCount = pasteboard.changeCount
        guard currentChangeCount != lastChangeCount else { return }
        lastChangeCount = currentChangeCount

        let protectedTypes = [
            "org.nspasteboard.ConcealedType",
            "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType",
        ]
        let availableTypes = Set((pasteboard.types ?? []).map(\.rawValue))
        guard protectedTypes.allSatisfy({ !availableTypes.contains($0) }),
              let content = pasteboard.string(forType: .string) else { return }

        let frontmost = NSWorkspace.shared.frontmostApplication
        do {
            if let clip = try store.enqueue(
                content: content,
                sourceApp: frontmost?.localizedName,
                bundleIdentifier: frontmost?.bundleIdentifier
            ) {
                onCapture?(clip)
            }
        } catch {
            NSLog("Clipboard+ could not store a clip: %@", error.localizedDescription)
        }
    }
}

@MainActor
final class AppDelegate: NSObject, NSApplicationDelegate {
    private let statusItem = NSStatusBar.system.statusItem(withLength: NSStatusItem.variableLength)
    private var store: CompanionStore!
    private var monitor: ClipboardMonitor!
    private var quickPaste: QuickPasteController!
    private var globalHotKey: GlobalHotKey?
    private let captureItem = NSMenuItem(title: "Capture system clipboard", action: #selector(toggleCapture), keyEquivalent: "")
    private let pendingItem = NSMenuItem(title: "0 clips waiting for Chrome", action: nil, keyEquivalent: "")
    private let lastCaptureItem = NSMenuItem(title: "No captures yet", action: nil, keyEquivalent: "")

    func applicationDidFinishLaunching(_ notification: Notification) {
        do {
            store = try CompanionStore()
            monitor = ClipboardMonitor(store: store)
            monitor.onCapture = { [weak self] clip in self?.didCapture(clip) }
            monitor.start()
            quickPaste = QuickPasteController(
                store: store,
                onPasteboardWrite: { [weak self] in self?.monitor.notePasteboardWrite() },
                onStatus: { [weak self] status in self?.showStatus(status) }
            )
            configureMenu()
            do {
                globalHotKey = try GlobalHotKey { [weak self] in self?.quickPaste.show() }
            } catch {
                NSLog("Clipboard+ could not register Quick Paste: %@", error.localizedDescription)
                showStatus(error.localizedDescription)
            }
            refreshMenu()
        } catch {
            let alert = NSAlert()
            alert.messageText = "Clipboard+ could not start"
            alert.informativeText = error.localizedDescription
            alert.runModal()
            NSApplication.shared.terminate(nil)
        }
    }

    private func configureMenu() {
        statusItem.button?.title = "C+"
        statusItem.button?.toolTip = "Clipboard+ universal capture"
        let menu = NSMenu()
        let heading = NSMenuItem(title: "Clipboard+ Companion", action: nil, keyEquivalent: "")
        heading.isEnabled = false
        menu.addItem(heading)
        let quickPasteItem = NSMenuItem(title: "Open Quick Paste", action: #selector(openQuickPaste), keyEquivalent: "v")
        quickPasteItem.keyEquivalentModifierMask = [.control, .shift]
        quickPasteItem.target = self
        menu.addItem(quickPasteItem)
        let accessibilityItem = NSMenuItem(title: "Open Accessibility Settings", action: #selector(openAccessibilitySettings), keyEquivalent: "")
        accessibilityItem.target = self
        menu.addItem(accessibilityItem)
        menu.addItem(.separator())
        captureItem.target = self
        menu.addItem(captureItem)
        pendingItem.isEnabled = false
        menu.addItem(pendingItem)
        lastCaptureItem.isEnabled = false
        menu.addItem(lastCaptureItem)
        menu.addItem(.separator())
        let pauseItem = NSMenuItem(title: "Pause for 5 minutes", action: #selector(pauseTemporarily), keyEquivalent: "")
        pauseItem.target = self
        menu.addItem(pauseItem)
        menu.addItem(.separator())
        let quitItem = NSMenuItem(title: "Quit Companion", action: #selector(quit), keyEquivalent: "q")
        quitItem.target = self
        menu.addItem(quitItem)
        statusItem.menu = menu
    }

    private func refreshMenu() {
        guard let state = try? store.read() else { return }
        captureItem.state = state.settings.captureEnabled ? .on : .off
        pendingItem.title = "\(state.pendingClips.count) clip\(state.pendingClips.count == 1 ? "" : "s") waiting for Chrome"
    }

    private func didCapture(_ clip: NativeClip) {
        lastCaptureItem.title = "Last: \(clip.sourceApp ?? "Unknown app")"
        refreshMenu()
    }

    private func showStatus(_ status: String) {
        lastCaptureItem.title = status
        refreshMenu()
    }

    @objc private func openQuickPaste() {
        quickPaste.show()
    }

    @objc private func openAccessibilitySettings() {
        let path = "x-apple.systempreferences:com.apple.preference.security?Privacy_Accessibility"
        if let url = URL(string: path) { NSWorkspace.shared.open(url) }
    }

    @objc private func toggleCapture() {
        guard var state = try? store.read() else { return }
        state.settings.captureEnabled.toggle()
        try? store.setCaptureEnabled(state.settings.captureEnabled)
        refreshMenu()
    }

    @objc private func pauseTemporarily() {
        try? store.setCaptureEnabled(false)
        refreshMenu()
        DispatchQueue.main.asyncAfter(deadline: .now() + 300) { [weak self] in
            try? self?.store.setCaptureEnabled(true)
            self?.refreshMenu()
        }
    }

    @objc private func quit() {
        NSApplication.shared.terminate(nil)
    }

    func applicationWillTerminate(_ notification: Notification) {
        globalHotKey?.invalidate()
    }
}

let application = NSApplication.shared
let delegate = AppDelegate()
application.delegate = delegate
application.setActivationPolicy(.accessory)
application.run()
